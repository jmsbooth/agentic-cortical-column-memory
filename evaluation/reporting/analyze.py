"""Produce machine-readable summaries and a generated LaTeX table."""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path
from typing import Any

from evaluation.metrics.metrics import summarize_records
from evaluation.reporting.figures import write_success_bar_chart


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    with path.open(encoding="utf-8") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def _write_table(summary: dict[str, Any], path: Path) -> None:
    rows = [
        (strategy, values["task_success_rate"], values["false_consensus_rate"], values["mean_model_invocations"])
        for strategy, values in sorted(summary["strategies"].items())
    ]
    lines = [
        "% Generated by evaluation.reporting.analyze; do not edit manually.",
        "\\begin{tabular}{lrrr}",
        "\\toprule",
        "Strategy & Success rate & False consensus & Model calls \\\\",
        "\\midrule",
    ]
    for strategy, success, false_consensus, calls in rows:
        lines.append(f"{strategy} & {success:.3f} & {false_consensus:.3f} & {calls:.1f} \\\\")
    lines.extend(["\\bottomrule", "\\end{tabular}", ""])
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path)
    parser.add_argument("--output-dir", type=Path, default=Path("results/processed"))
    args = parser.parse_args()
    records = read_jsonl(args.input)
    summary = summarize_records(records)
    args.output_dir.mkdir(parents=True, exist_ok=True)
    (args.output_dir / "summary.json").write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    write_success_bar_chart(summary, args.output_dir / "strategy_success.svg")
    with (args.output_dir / "summary.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(["strategy", "n", "task_success_rate", "false_consensus_rate", "mean_model_invocations"])
        for strategy, values in sorted(summary["strategies"].items()):
            writer.writerow([strategy, values["n"], values["task_success_rate"], values["false_consensus_rate"], values["mean_model_invocations"]])
    _write_table(summary, Path("paper/tables/smoke_summary.tex"))
    print(json.dumps({"record_count": summary["record_count"], "strategies": sorted(summary["strategies"])}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
